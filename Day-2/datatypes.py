a = 5        # Integer
b = 10.4     # Float
c = "Gouri"  # String
d = True     # Boolean
e = None     # NoneType
f = 1j       # Complex Number
g = 35e3     # Scientific Notation (Float)

print(type(a))  # Prints <class 'int'>
print(type(b))  # Prints <class 'float'>
print(type(c))  # Prints <class 'str'>
print(type(d))  # Prints <class 'bool'>
print(type(e))  # Prints <class 'NoneType'>
print(type(f))  # Prints <class 'complex'>
print(type(g))  # Prints <class 'float'>